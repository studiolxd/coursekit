"""`coursekit agents`: render skills, commands, agents and docs for Claude Code, opencode and Codex.

One source: the package files (coursekit/agentkit/) plus the project overrides in `.agents/`
(same layout: `skills/<name>/SKILL.md`, `commands/<name>.md`, `agents/<name>.md`; a project file
replaces the package file of the same name). Every file is rendered with the project values
(`{{name}}` tokens, `{{> partial}}` includes) and written as a copy where each tool reads it:

    .claude/skills/<name>/SKILL.md    .claude/commands/<name>.md
    .opencode/skill/<name>/SKILL.md   .opencode/command/<name>.md   .opencode/agent/<name>.md
    .coursekit/agents/...             (Codex and any other tool: listed in AGENTS.md)
    .coursekit/docs/...               (content format, slxd reference)

and the tool configuration is merged (never replaced) into `.mcp.json`, `opencode.json`,
`.claude/settings.json` and `.codex/config.toml`: the slxd MCP server, and agents denied to run
`coursekit approve` and `git push`. Only files coursekit generated (they carry a marker) are
overwritten or removed.
"""

