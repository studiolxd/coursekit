def project_audience(data: dict) -> str:
    """`project.yaml › audience`, as the skills give it (what is empty is said to be missing)."""
    given = data.get("audience") if isinstance(data.get("audience"), dict) else {}
    lines = [f"{key}: {str(given.get(key) or '').strip() or '(not set)'}" for key in coursemod.AUDIENCE_KEYS]
    return "; ".join(lines)


def assessment_delivery_rule(project: Project) -> str:
    """Where the tests go and in which format (`delivery › assessment`), as the skills tell it."""
    cfg = config.effective("delivery", project).value.get("assessment") or {}
    placement, fmt = str(cfg.get("placement") or "unit"), str(cfg.get("format") or "platform")
    backend = str((config.project_data(project).get("assembly") or {}).get("backend") or "creator")
    where = ("in the package of their unit" if placement == "unit" else
             "apart, in one package of their own after the units (one more unit to assemble and deliver)")
    if fmt == "platform":
        how = "as evaluation lessons of the package"
    else:
        how = (f"as a {fmt} question bank the LMS imports (exported by creator with the creator backend, written by `coursekit "
               f"delivery questions` with html or in aiken): the question bank of assessment.md may use only "
               f"{', '.join(coursemod.bank_questions(fmt, backend))}; scored simulations stay in a package")
    return (f"the tests go {where}, {how} (`delivery › assessment`: placement {placement}, format {fmt}; a course may set its own, "
            "see `coursekit config delivery --course <CODE>`)")


def project_skins(project: Project) -> str:
    """The skins of the project (components/skins/), as the content format lists them for the writer."""
    from coursekit import simulation as simmod

    simmod.use_project_skins(project.root)
    own = [name for name in simmod.SKINS if name not in simmod.BUILTIN_SKINS]
    if not own:
        return "none"
    return "; ".join(f"`{name}` (screen: {', '.join(sorted(simmod.SCREEN_KEYS[name])) or '-'}; targets: "
                     f"{', '.join(x + 'N' if x.endswith(':') else x for x in simmod.TARGETS[name]) or '-'}"
                     f"{'; chat' if name in simmod.CHAT_SKINS else ''})" for name in own)


def readability_tokens(cfg: dict) -> dict[str, str]:
    """The readability the audience of the project's courses asks for (rules › readability)."""
    audience = str(cfg.get("audience") or "general")
    return {
        "readability_audience": audience,
        "long_sentence_words": str((cfg.get("long_sentence_words") or {}).get(audience, "")),
        "readability_min_index": str((cfg.get("min_index") or {}).get(audience, "")),
    }


def decision_tokens(cfg: dict) -> dict[str, str]:
    """The rules of decision-based courses for the skills (rules › decision_based)."""
    optional = set(cfg.get("optional") or [])
    return {
        "decision_cycle": " → ".join(f"{part} (optional)" if part in optional else str(part) for part in cfg.get("cycle") or []),
        "min_simulations_per_content_section": str(cfg.get("min_simulations_per_content_section", 1)),
        "simulation_rewind": "on" if cfg.get("rewind", True) else "off",
        "decision_seconds": f"{float(cfg.get('decision_seconds', 0)):g}",
    }


def render(text: str, values: dict[str, str], partials: dict[str, str], where: str = "") -> str:
    def include(m: re.Match) -> str:
        name = m.group(1)
        if name not in partials:
            raise RenderError(t("agents", "unknown_partial", where=where, name=name))
        return partials[name].strip()

    text = PARTIAL.sub(include, text)

    def token(m: re.Match) -> str:
        name = m.group(1)
        if name not in values:
            raise RenderError(t("agents", "unknown_token", where=where, name=name))
        return values[name]

    return TOKEN.sub(token, text)


def _package_dir() -> Path:
    return Path(str(resources.files("coursekit.agentkit")))


def collect(project: Project) -> tuple[dict[str, dict[str, Path]], dict[str, str]]:
    """Source files per kind ({name: path}), project overrides winning; and the partials."""
    roots = [_package_dir(), project.root / ".agents"]
    found: dict[str, dict[str, Path]] = {k: {} for k in KINDS}
    partials: dict[str, str] = {}
    for root in roots:
        for kind in KINDS:
            folder = root / kind
            if not folder.is_dir():
                continue
            for entry in sorted(folder.iterdir()):
                if entry.name.startswith(".") or entry.name == "__init__.py" or entry.name == "__pycache__":
                    continue
                if entry.name.startswith("_") and entry.suffix == ".md":
                    partials[entry.stem] = entry.read_text(encoding="utf-8")
                    continue
                if kind == "skills" and entry.is_dir() and (entry / "SKILL.md").exists():
                    found[kind][entry.name] = entry
                elif kind != "skills" and entry.suffix == ".md":
                    found[kind][entry.stem] = entry
    return found, partials


def _mark(text: str, source: str) -> str:
    note = f"<!-- {MARKER}; {source} -->"
    if text.startswith("---"):
        end = text.index("---", 3) + 3
        return text[:end] + "\n" + note + text[end:]
    return note + "\n" + text


def _is_managed(path: Path) -> bool:
    if path.is_dir():
        path = path / "SKILL.md"
    try:
        return path.is_file() and MARKER in path.read_text(encoding="utf-8", errors="ignore")[:4000]
    except OSError:
        return False


def _write(path: Path, text: str, report: Report, root: Path) -> None:
    rel = path.relative_to(root).as_posix()
    if path.exists() and not _is_managed(path):
        report.kept.append(rel)
        return
    if path.exists() and path.read_text(encoding="utf-8") == text:
        report.unchanged += 1
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    report.written.append(rel)


def _agent_text(text: str, name: str) -> str:
    """opencode agents carry the model of their role when that role uses opencode."""
    tool, model = role(name)
    lines = text.splitlines(keepends=True)
    if tool == "opencode" and model:
        return "".join(line.replace("{{model}}", model) for line in lines)
    return "".join(line for line in lines if "{{model}}" not in line)  # the tool's default model


def targets(kind: str, name: str) -> list[Path]:
    if kind == "skills":
        return [Path(".claude/skills") / name / "SKILL.md", Path(".opencode/skill") / name / "SKILL.md",
                Path(".coursekit/agents/skills") / name / "SKILL.md"]
    if kind == "commands":
        return [Path(".claude/commands") / f"{name}.md", Path(".opencode/command") / f"{name}.md",
                Path(".coursekit/agents/commands") / f"{name}.md"]
    if kind == "agents":
        return [Path(".opencode/agent") / f"{name}.md"]
    return [Path(".coursekit/docs") / f"{name}.md"]


GENERATED_DIRS = {
    "skills": [".claude/skills", ".opencode/skill", ".coursekit/agents/skills"],
    "commands": [".claude/commands", ".opencode/command", ".coursekit/agents/commands"],
    "agents": [".opencode/agent"],
    "docs": [".coursekit/docs"],
}


def generate(project: Project) -> Report:
    root = project.root
    values = context(project)
    sources, partials = collect(project)
    report = Report()
    for kind in KINDS:
        for name, source in sources[kind].items():
            path = source / "SKILL.md" if kind == "skills" else source
            package = _package_dir() in path.parents
            origin = (f"to change it, add an override in .agents/{kind}/" if package
                      else f"edit {path.relative_to(root).as_posix()}")
            text = path.read_text(encoding="utf-8")
            if kind == "agents":
                text = _agent_text(text, name)
            text = _mark(render(text, values, partials, path.name), origin)
            for target in targets(kind, name):
                _write(root / target, text, report, root)
            if kind == "skills":  # other files of a skill folder (examples, assets) are copied as they are
                for extra in source.rglob("*"):
                    if extra.is_file() and extra.name not in ("SKILL.md", "__init__.py") and "__pycache__" not in extra.parts:
                        for target in targets(kind, name):
                            dest = root / target.parent / extra.relative_to(source)
                            dest.parent.mkdir(parents=True, exist_ok=True)
                            shutil.copyfile(extra, dest)
        expected = set(sources[kind]) if kind == "skills" else {f"{n}.md" for n in sources[kind]}
        for folder in GENERATED_DIRS[kind]:
            base = root / folder
            if not base.is_dir():
                continue
            for entry in sorted(base.iterdir()):
                if entry.name not in expected and _is_managed(entry):
                    shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
                    report.removed.append(entry.relative_to(root).as_posix())
    report.configs = write_configs(project, values)
    return report


