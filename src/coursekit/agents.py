TOKEN = re.compile(r"\{\{\s*([a-z_][a-z0-9_]*)\s*\}\}")
PARTIAL = re.compile(r"\{\{>\s*([a-z0-9_-]+)\s*\}\}")


class RenderError(Exception):
    pass


@dataclass
class Report:
    written: list[str] = field(default_factory=list)
    unchanged: int = 0
    removed: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)
    configs: list[str] = field(default_factory=list)


def role(name: str) -> tuple[str, str]:
    """(tool, model) of a role from the environment (.env): <ROLE>_AGENT / <ROLE>_MODEL; a role with `same_as` and both empty
    takes those of the other role."""
    key = name.upper()
    base = same_as(name)
    if base and not (os.environ.get(f"{key}_AGENT") or "").strip() and not (os.environ.get(f"{key}_MODEL") or "").strip():
        return role(base)
    tool = (os.environ.get(f"{key}_AGENT") or "claude").strip().lower()
    return tool, (os.environ.get(f"{key}_MODEL") or "").strip()


def role_defaults() -> dict:
    text = resources.files("coursekit.defaults").joinpath("agents.yaml").read_text(encoding="utf-8")
    return (yaml.safe_load(text) or {}).get("roles") or {}


def same_as(name: str) -> str | None:
    """The role whose tool and model this one takes while its own variables are empty (`same_as` in agents.yaml)."""
    base = (role_defaults().get(name) or {}).get("same_as")
    return str(base) if base else None


def default_tool(name: str) -> str:
    base = same_as(name)
    return default_tool(base) if base else str((role_defaults().get(name) or {}).get("tool") or "claude")


def default_model(name: str, tool: str) -> str:
    """The model proposed for a role with a tool; empty when the tool's own default is the best choice."""
    base = same_as(name)
    if base:
        return default_model(base, tool)
    return str(((role_defaults().get(name) or {}).get("models") or {}).get(tool) or "")


def server_key(name: str) -> str:
    """How Claude Code writes the name of an MCP server in the names of its tools (`mcp__<key>__<tool>`)."""
    return re.sub(r"[^A-Za-z0-9_-]", "_", name)


def connector_server(project: Project) -> str | None:
    """Key of the claude.ai connector of creator that the person logged in at account level, when the project says to use it
    (project.yaml › platform.slxd.connector: its name as Claude Code lists it, with or without the "claude.ai " prefix)."""
    slxd = (config.project_data(project).get("platform") or {}).get("slxd") or {}
    name = str(slxd.get("connector") or "").strip()
    if not name:
        return None
    return server_key(name if name.lower().startswith("claude.ai") else f"claude.ai {name}")


